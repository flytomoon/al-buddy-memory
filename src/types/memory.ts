/**
 * GOV-DAT-001 §2.1 — Canonical memory node types.
 * `Narrative` supports long-form prose preservation summaries (§3.6).
 */
export const MEMORY_NODE_TYPES = [
  "Experience", // Episodic — something that happened
  "Lesson", // Semantic — something learned
  "Conversation", // Verbatim or summarized dialogue
  "Belief", // Value, opinion, or conviction
  "Relationship", // A person, group, or entity the user relates to
  "Skill", // Procedural — something the user can do
  "Narrative", // Long-form prose preservation summary (§3.6)
] as const;
export type MemoryNodeType = (typeof MEMORY_NODE_TYPES)[number];

/**
 * GOV-DAT-001 §2.1 — How a node entered the system.
 */
export const MEMORY_PROVENANCES = [
  "UserInput", // Directly authored by the user
  "AIInferred", // Derived/generated by the AI system
  "GuardianAdded", // Added by a designated guardian (under-age accounts)
  "SystemGenerated", // Automated system operation (e.g., session summaries)
] as const;
export type MemoryProvenance = (typeof MEMORY_PROVENANCES)[number];

/**
 * GOV-DAT-001 §2.3 — Controls AI access and external sharing.
 *
 * Phase 1: field is required; classification is informational.
 * Phase 2: enforcement is active — Sealed nodes are excluded from AI context.
 */
export const PRIVACY_CLASSIFICATIONS = [
  "Public", // Shareable with user, AI, and designated advisors
  "Private", // Default — accessible to user and AI only
  "Sensitive", // Excluded from summarization unless user explicitly opts in
  "Sealed", // AI may not read, reference, or summarize
] as const;
export type PrivacyClassification = (typeof PRIVACY_CLASSIFICATIONS)[number];

/**
 * GOV-DAT-001 §3.2 — Retention tier lifecycle.
 */
export const RETENTION_TIERS = [
  "FullRetention", // Stored in original form, fully indexed and searchable
  "Summarized", // Reserved. Raw content is NOT replaced: a summary is a new Narrative node
  "Archived", // Cold storage; excluded from active AI context by default
  "PendingDeletion", // 14-day grace period before irreversible destruction
] as const;
export type RetentionTier = (typeof RETENTION_TIERS)[number];

// ---------------------------------------------------------------------------
// Memory Node — GOV-DAT-001 §2.1
// ---------------------------------------------------------------------------

/**
 * A timestamped event in a node's temporal lifecycle.
 * The `temporalAnchors` array is append-only — entries are never removed.
 */
export const ANCHOR_EVENTS = ["created", "recalled", "reinforced", "modified", "summarized", "archived"] as const;

export interface TemporalAnchor {
  timestamp: string; // ISO 8601
  event: (typeof ANCHOR_EVENTS)[number];
}

/**
 * Structured content payload. Phase 1 requires only `text`.
 * `structuredData` and `attachmentRefs` are reserved for Phase 2.
 */
export interface MemoryContent {
  text: string;
  structuredData?: Record<string, unknown>; // Phase 2: typed sub-fields per memoryType
  attachmentRefs?: string[]; // Phase 2: references to attached files/media
}

/**
 * GOV-DAT-001 §2.1 — A memory node in the ALBUDDY semantic graph.
 *
 * Immutable fields (`readonly`) must not change after creation.
 * All timestamps are ISO 8601 strings to remain JSON-serializable and LLM-agnostic.
 */
export interface MemoryNode {
  // --- Identity (immutable) ---
  readonly nodeId: string; // UUID v4 — stable across all storage layers
  readonly provenance: MemoryProvenance; // How this node entered the system
  readonly encryptionKeyRef: string; // Reference to the user-controlled encryption key

  // --- Classification ---
  memoryType: MemoryNodeType;
  privacyClassification: PrivacyClassification; // Default: "Private"
  retentionTier: RetentionTier; // Default: "FullRetention"

  // --- Content ---
  content: MemoryContent;
  contextualMetadata: Record<string, unknown>; // Tags, themes, user-added labels

  // --- Temporal: transaction time (§2.1 temporalAnchors — append-only) ---
  // WHEN THE SYSTEM recorded events about this node (created/recalled/modified…).
  temporalAnchors: TemporalAnchor[];

  // --- Temporal: valid time (bi-temporal, v1.1.0) ---
  // WHEN THE FACT IS TRUE IN THE WORLD, independent of when we recorded it.
  // A superseded fact is NOT deleted — it keeps its node and gets `validTo` set,
  // so the graph records how the user's life changed over time
  // (e.g. "lived in London" gets a validTo when they move to Tokyo).
  // The store defaults `validFrom` to creation time and `validTo` to null (open).
  validFrom: string; // ISO 8601 — when the fact became true.
  validTo: string | null; // ISO 8601, or null for open-ended / still true.

  // --- Confidence & Decay (§3.5) ---
  confidenceWeight: number; // Float [0.0–1.0] — estimated freshness/relevance
  decayRate: number; // Rate at which confidence degrades without reinforcement

  /**
   * @deprecated Since 1.1.0. Inline embeddings are frozen — vectors now live in
   * the dedicated {@link MemoryEmbedding} side store (see `setEmbedding`), tagged
   * with the model that produced them so they stay a disposable, re-embeddable
   * cache. Raw `content.text` remains the source of truth. Do not write this field.
   */
  embedding?: number[];
}

/**
 * Input to {@link MemoryStore.addNode}. The store assigns `nodeId` and the
 * initial `temporalAnchors`, and defaults valid-time when not supplied
 * (`validFrom` → creation time, `validTo` → null). Callers MAY still provide
 * valid-time explicitly for facts that were true before they were recorded
 * (e.g. "I moved to Tokyo in 2020").
 */
export type NewMemoryNode = Omit<
  MemoryNode,
  "nodeId" | "temporalAnchors" | "validFrom" | "validTo"
> & {
  validFrom?: string;
  validTo?: string | null;
};


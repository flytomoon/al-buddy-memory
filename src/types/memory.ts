export interface MemoryQueryOptions {
  memoryType?: MemoryNodeType | MemoryNodeType[];
  privacyClassification?: PrivacyClassification[];
  retentionTier?: RetentionTier[];
  tags?: string[];
  minConfidence?: number;
  query?: string; // Semantic / full-text search string
  /**
   * Bi-temporal filter: return only nodes whose valid-time window contains this
   * instant — `validFrom <= validAt AND (validTo IS NULL OR validTo > validAt)`.
   * Omit to ignore valid-time (returns nodes regardless of whether superseded).
   */
  validAt?: string; // ISO 8601
  limit?: number;
  after?: string; // Cursor-based pagination (nodeId)
}

/** A whole memory graph as one state of a store: every node, every edge. */
export interface GraphSnapshot {
  nodes: MemoryNode[];
  edges: MemoryEdge[];
}

/** The complete mutable image of a fact. Keep this list aligned with updateNode. */
export const MUTABLE_NODE_FIELDS = [
  "memoryType",
  "privacyClassification",
  "retentionTier",
  "contextualMetadata",
  "validFrom",
  "validTo",
  "confidenceWeight",
  "decayRate",
] as const;
export type MutableNodeState = Pick<MemoryNode, (typeof MUTABLE_NODE_FIELDS)[number]>;

/** Transaction-history events. `restored` exists only in version history. */
export const VERSION_EVENTS = [...ANCHOR_EVENTS, "restored"] as const;

/** One store change, with full images on both sides of it. */
export interface NodeVersion {
  readonly versionId: string;
  readonly nodeId: string;
  readonly recordedAt: string;
  readonly event: (typeof VERSION_EVENTS)[number];
  readonly before: MutableNodeState;
  readonly after: MutableNodeState;
}

export interface AsOfSnapshot extends GraphSnapshot {
  readonly asOf: string;
  /** Facts whose state at `asOf` the recorded history cannot vouch for (see `exact`). */
  readonly inexact: string[];
}

/** One fact as the store held it at an instant. */
export interface AsOfFact {
  readonly node: MemoryNode;
  /**
   * false when the recorded history does not account for the fact from that
   * instant to now: changes made before 0.5.0 (or by an older library), a
   * write policy that reshaped an imported fact, or two stores' histories
   * joined by an import. The node is then the best the history supports, not
   * a guarantee.
   */
  readonly exact: boolean;
}

/** Filters for an as-of read. */
export interface AsOfOptions {
  /** Keep only facts whose valid-time window, as the store held it at `asOf`, contains this instant. */
  validAt?: string;
}

/** Optional transaction-history capability. MemoryStore itself stays unchanged. */
export interface HistoryCapable {
  /** Every recorded change to one fact, in the order the changes happened. [] if unknown or erased. */
  history(nodeId: string): Promise<NodeVersion[]>;
  /** One fact as the store held it at `asOf`, and whether history vouches for it; undefined if not yet learned, or erased. */
  getNodeAsOf(nodeId: string, asOf: string): Promise<AsOfFact | undefined>;
  /** The whole graph as the store held it at `asOf`, read as one state; `validAt` combines the two time axes. */
  snapshotAsOf(asOf: string, options?: AsOfOptions): Promise<AsOfSnapshot>;
  historySnapshot(): Promise<GraphSnapshot & { versions: NodeVersion[] }>;
  restoreVersion(version: NodeVersion): Promise<void>;
}

/**
 * An optional capability, not part of {@link MemoryStore}: the whole graph read
 * as ONE state, for export and backup. Both shipped stores implement it (SQLite
 * inside a read transaction, the in-memory store without an await inside), so
 * `exportPortable` produces a graph the store actually had rather than nodes
 * from one instant and edges from another. A store that does not implement it
 * still exports, with the weaker guarantee named in `memory-portability.ts`.
 */
export interface SnapshotCapable {
  snapshot(): Promise<GraphSnapshot>;
}

/**
 * Storage-agnostic interface for the memory graph.
 * Implementations may be local SQLite, Neptune, Neo4j, or an in-memory store —
 * the API surface does not change.
 */
export interface MemoryStore {
  // Node operations
  addNode(node: NewMemoryNode): Promise<MemoryNode>;
  getNode(nodeId: string): Promise<MemoryNode | undefined>;
  searchNodes(options: MemoryQueryOptions): Promise<MemoryNode[]>;
  /**
   * EVERY node the store holds — any validity, privacy classification or
   * retention tier — oldest learned first, then by id. The enumeration
   * primitive for export, backup and administration; not a recall path, and
   * none of searchNodes' default exclusions apply. (Export used to enumerate
   * through searchNodes and silently lost every Archived fact.)
   */
  listNodes(): Promise<MemoryNode[]>;
  updateNode(
    nodeId: string,
    // Not content: raw text is immutable. The exported field tuple is the
    // single source of truth, so history images and patches cannot drift.
    patch: Partial<MutableNodeState>,
    /** Lifecycle event to record on the appended anchor. Default "modified";
     *  pass "reinforced" when a duplicate observation strengthens the node. */
    anchorEvent?: TemporalAnchor["event"],
  ): Promise<MemoryNode>;
  deleteNode(nodeId: string): Promise<void>;

  // Portability — verbatim restore for round-trip import (nodeId, anchors,
  // and valid-time preserved exactly; never generates new identity).
  restoreNode(node: MemoryNode): Promise<void>;
  restoreEdge(edge: MemoryEdge): Promise<void>;

  // Edge operations (Phase 1: store/retrieve; Phase 2: full traversal)
  addEdge(edge: Omit<MemoryEdge, "edgeId" | "createdAt">): Promise<MemoryEdge>;
  getEdges(nodeId: string): Promise<MemoryEdge[]>;
  deleteEdge(edgeId: string): Promise<void>;

  // Embedding operations — a disposable, model-tagged vector cache (v1.1.0).
  /** Upsert the embedding for `(nodeId, model)`. Re-embedding with the same
   *  model replaces the vector; a different model coexists alongside it. */
  setEmbedding(embedding: Omit<MemoryEmbedding, "createdAt">): Promise<MemoryEmbedding>;
  /** All embeddings held for a node, one per model. */
  getEmbeddings(nodeId: string): Promise<MemoryEmbedding[]>;
  /** All embeddings for one model across the whole store (vector-scan input). */
  listEmbeddings(model: string): Promise<MemoryEmbedding[]>;
  /** Drop a node's embeddings — all of them, or just one model's. */
  deleteEmbeddings(nodeId: string, model?: string): Promise<void>;
}


/**
 * Core memory schema for ALBUDDY — the canonical contract binding memory
 * storage, the read/write API (ALB-7), and all future UI layers.
 *
 * Aligned with GOV-DAT-001 §2 (Memory Node Anatomy, Relationship Edge Anatomy).
 *
 * Phase 1 (MVP): Full node schema; edges stored but graph traversal deferred.
 * Phase 2: Full bidirectional graph traversal, active privacy-tier enforcement,
 *          automated decay/archival pipelines.
 *
 * @version 1.1.0
 * @see docs/architecture/memory-schema.md
 *
 * ## Changelog
 * - 1.1.0 — Bi-temporal validity (`validFrom`/`validTo`) so a superseded fact is
 *   invalidated, not deleted; the graph records how knowledge changed over time.
 *   Embeddings moved to a dedicated, model-tagged {@link MemoryEmbedding} side
 *   store (disposable, re-embeddable cache); inline `MemoryNode.embedding` is
 *   deprecated. Portability review (2026-07-07) — see
 *   docs/architecture/memory-architecture-decision.md.
 * - 1.0.0 — Canonical node/edge schema (ALB-2), aligned with GOV-DAT-001 §2.
 */

